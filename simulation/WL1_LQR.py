import numpy as np
import control as ct

# --- 1. 参数定义 ---
m = 0.4155        # 参与俯仰的重量 (kg)
h = 0.034        # 长度 (m)——0.0525是中间点  0.071是最高点  0.034是最低点
I = m * (h**2)   # 转动惯量
g = 9.8          # 重力加速度
r = 0.022        # 轮子半径 (m)
M = 0.0326       # 不参与俯仰的重量 (kg)

# 计算中间变量 D
D = (M + m) * (m * h**2 + I) - m**2 * h**2

# --- 2. 构建状态空间矩阵 ---
# A 矩阵 (4x4)
A = np.array([
    [0, 1, 0, 0],
    [((M + m) * m * g * h) / D, 0, 0, 0],
    [0, 0, 0, 1],
    [-(m**2 * g * h**2) / D, 0, 0, 0]
])

# B 矩阵 (4x1)
B = np.array([
    [0],
    [-(m * h) / (D * r)],
    [0],
    [1 / ((M + m) * r) - (m**2 * h**2) / ((M + m) * D * r)]
])

# --- 3. 定义权重矩阵 ---
Q = np.diag([10.0, 10.0, 0, 0])  # 状态权重矩阵 (4x4)
R = np.array([[0.5]])  # 控制权重矩阵 (1x1)

# --- 4. LQR 解算 ---
# K: 反馈增益矩阵, S: 黎卡提方程的解, E: 闭环特征值
K, S, E = ct.lqr(A, B, Q, R)

# --- 5. 结果打印 (C 风格数组格式) ---
print(f"// h = {h}, m = {m}")
print("float K[4] = {", end="")
# 将矩阵展开为一维并格式化输出
k_values = K.flatten()
print(", ".join([f"{val:.6f}f" for val in k_values]), end="")
print("};")